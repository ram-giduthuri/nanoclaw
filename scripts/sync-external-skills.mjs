#!/usr/bin/env node
/**
 * Sync selected skills from Ram's claude-plugins marketplace into
 * container/skills/ so nanoclaw agents can use them.
 *
 * Single source of truth is the claude-plugins repo. The copies written here
 * are generated artifacts and are gitignored via a managed block in
 * container/skills/.gitignore.
 *
 * Config: container/external-skills.json
 *   - source:  path to the claude-plugins checkout (relative to repo root, or absolute).
 *              Override with env NANOCLAW_EXTERNAL_SKILLS_SRC.
 *   - all:     if true, sync every plugin's skills; otherwise only `skills`.
 *   - skills:  [{ plugin, skill }] to sync (skill = folder under plugins/<plugin>/skills/).
 *
 * Safety: an existing skill dir that this script did not create on a prior run
 * (i.e. one of nanoclaw's own native skills) is NEVER overwritten — those are
 * skipped with a warning. The .gitignore is edited only within a managed block,
 * so any hand-authored rules are preserved.
 *
 * Usage: npm run sync-skills
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');
const skillsDir = path.join(repoRoot, 'container', 'skills');
const configPath = path.join(repoRoot, 'container', 'external-skills.json');

const BEGIN = '# BEGIN synced external skills (generated by scripts/sync-external-skills.mjs)';
const END = '# END synced external skills';

function fail(msg) {
  console.error(`sync-external-skills: ${msg}`);
  process.exit(1);
}

function escapeRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, String.raw`\$&`);
}

/**
 * Names this script synced on a previous run, read from the managed block in
 * container/skills/.gitignore (falling back to the old fully-generated format).
 * A skill dir that already exists but is NOT in this set is treated as foreign
 * (e.g. one of nanoclaw's own native skills) and never overwritten — no external
 * process needed.
 */
function previouslySyncedNames() {
  const gi = path.join(skillsDir, '.gitignore');
  if (!fs.existsSync(gi)) return new Set();
  const content = fs.readFileSync(gi, 'utf8');
  const start = content.indexOf(BEGIN);
  const scope =
    start === -1 ? content : content.slice(start, content.indexOf(END, start));
  const names = new Set();
  for (const line of scope.split('\n')) {
    const t = line.trim();
    if (t && !t.startsWith('#')) names.add(t.replace(/\/$/, ''));
  }
  return names;
}

/** Rewrite only our managed block in container/skills/.gitignore, preserving the rest. */
function updateGitignore(names) {
  const gi = path.join(skillsDir, '.gitignore');
  const block = [BEGIN, ...names.map((n) => `${n}/`), END].join('\n');
  let existing = fs.existsSync(gi) ? fs.readFileSync(gi, 'utf8') : '';
  // Migrate the old fully-generated file (pre managed-block format).
  if (
    !existing.includes(BEGIN) &&
    existing.startsWith('# Generated by scripts/sync-external-skills.mjs')
  ) {
    existing = '';
  }
  if (existing.includes(BEGIN)) {
    const re = new RegExp(String.raw`${escapeRe(BEGIN)}[\s\S]*?${escapeRe(END)}\n?`);
    existing = existing.replace(re, block + '\n');
  } else {
    const prefix = existing.trim() ? existing.trimEnd() + '\n\n' : '';
    existing = prefix + block + '\n';
  }
  fs.writeFileSync(gi, existing);
}

if (!fs.existsSync(configPath)) fail(`missing config ${configPath}`);
const config = JSON.parse(fs.readFileSync(configPath, 'utf8'));

const sourceRoot = path.resolve(
  repoRoot,
  process.env.NANOCLAW_EXTERNAL_SKILLS_SRC || config.source,
);
const pluginsRoot = path.join(sourceRoot, 'plugins');
if (!fs.existsSync(pluginsRoot)) {
  fail(
    `claude-plugins not found at ${pluginsRoot} (set NANOCLAW_EXTERNAL_SKILLS_SRC or fix "source")`,
  );
}

// Resolve the list of {plugin, skill} to sync.
let entries = [];
if (config.all) {
  for (const plugin of fs.readdirSync(pluginsRoot)) {
    const skillsRoot = path.join(pluginsRoot, plugin, 'skills');
    if (!fs.existsSync(skillsRoot)) continue;
    for (const skill of fs.readdirSync(skillsRoot)) {
      if (fs.statSync(path.join(skillsRoot, skill)).isDirectory()) {
        entries.push({ plugin, skill });
      }
    }
  }
} else {
  entries = config.skills || [];
}

const known = previouslySyncedNames();
const synced = [];
for (const { plugin, skill } of entries) {
  const dst = path.join(skillsDir, skill);
  if (fs.existsSync(dst) && !known.has(skill)) {
    console.warn(
      `  skip ${plugin}/${skill}: "${skill}" already exists under container/skills and was not created by this sync — refusing to overwrite`,
    );
    continue;
  }
  const src = path.join(pluginsRoot, plugin, 'skills', skill);
  if (!fs.existsSync(path.join(src, 'SKILL.md'))) {
    console.warn(`  skip ${plugin}/${skill}: no SKILL.md at ${src}`);
    continue;
  }
  fs.rmSync(dst, { recursive: true, force: true });
  fs.cpSync(src, dst, { recursive: true });
  synced.push(skill);
  console.log(`  synced ${plugin}/${skill} -> container/skills/${skill}`);
}

updateGitignore(synced);
console.log(`sync-external-skills: ${synced.length} skill(s) synced.`);
